"""Writes lib/utils/mdi_icons.g.dart from the meta.json of @mdi/svg - the
icon names HA uses (`mdi:dishwasher`) mapped to the bundled font
(assets/fonts/materialdesignicons.ttf from @mdi/font, same version).

    curl -LO https://cdn.jsdelivr.net/npm/@mdi/svg@7.4.47/meta.json
    python3 tool/generate_mdi_icons.py meta.json
"""
import json
import sys

icons = json.load(open(sys.argv[1]))
entries = {}
for icon in icons:
    for name in [icon['name'], *icon.get('aliases', [])]:
        entries.setdefault(name, icon['codepoint'])

with open('lib/utils/mdi_icons.g.dart', 'w') as out:
    out.write('// Generated by tool/generate_mdi_icons.py - do not edit.\n\n')
    out.write("import 'package:flutter/widgets.dart';\n\n")
    out.write("const _font = 'MaterialDesignIcons';\n\n")
    out.write('/// Material Design Icons by name, as HA uses them without `mdi:`.\n')
    out.write('const mdiIcons = <String, IconData>{\n')
    for name in sorted(entries):
        out.write(f"  '{name}': IconData(0x{entries[name]}, fontFamily: _font),\n")
    out.write('};\n')
